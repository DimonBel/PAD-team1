def chip(d, x, y, w, h, title, body, kind="broker", badge=None, title_size=14, body_size=12):
    """A white card inside a bigger component, outlined in that component's colour."""
    return d.box(x, y, w, h, "note", title, body, title_size=title_size, body_size=body_size,
                 fill="#ffffff", stroke=KINDS[kind][1], sw=1.5, badge=badge)


def table(d, x, y, widths, rows, row_h=32, size=12, header_kind="infra", fills=None):
    """A grid of cells. rows[0] is the header. fills[i] colours data row i (a KINDS key)."""
    total = sum(widths)
    for r, row in enumerate(rows):
        ry = y + r * row_h
        if r == 0:
            f, s = KINDS[header_kind]
        else:
            f = KINDS[fills[r - 1]][0] if fills and fills[r - 1] else "#ffffff"
            s = "#ced4da"
        d.rect(x, ry, total, row_h, fill=f, stroke="#ced4da", sw=1, radius=0)
        cx = x
        for c, (w, cell) in enumerate(zip(widths, row)):
            d.text(cx + 10, ry + (row_h - size * 1.25) / 2, cell, size=size, bold=(r == 0 or c == 0),
                   color=INK if (r == 0 or c == 0) else MUTED)
            cx += w
    return y + len(rows) * row_h


