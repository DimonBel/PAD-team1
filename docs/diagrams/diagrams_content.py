NODE_COLORS = [("#d0ebff", "#1c7ed6"), ("#ffe8cc", "#e8590c"), ("#d3f9d8", "#2f9e44")]


def _ring_pos(key: str) -> float:
    """Position on the ring as an angle in radians, clockwise from the top (as in hash-ring.ts:
    the first 4 bytes of MD5)."""
    return int(hashlib.md5(key.encode()).hexdigest()[:8], 16) / 2 ** 32 * 2 * math.pi


def cache() -> Diagram:
    d = Diagram("03-cache-consistent-hashing", 1940, 1290, "Gateway cache · sharded by consistent hashing",
                "GET answers and sessions in 3 independent Redis nodes; the Gateway's own hash ring decides "
                "which node holds each key (Gateway-team1/docs/CONSISTENT_HASHING.md)")

    # gateway side
    d.zone(40, 110, 620, 640, "API GATEWAY · Gateway-team1/src/cache/", "edge")
    chip(d, 60, 150, 580, 125, "Sessions (authentication data)", [
        "login → gw:session:<jti> = { player_id, roles, opened_at }",
        "every request reads it: revoked → 401 SESSION_REVOKED",
        "POST /api/players/logout marks the session revoked",
        "miss → rebuilt from the signed token (nobody is logged out)",
    ], kind="edge")
    chip(d, 60, 295, 580, 125, "GET-answer cache", [
        "rules per route in config/routes.json (TTL 15–300 s)",
        "key gw:resp:<service>:g<generation>:<scope>:<path?query>",
        "scope roles = shared catalogue · caller = one player only",
        "only 200 answers · X-Cache: HIT / MISS / BYPASS",
    ], kind="edge")
    chip(d, 60, 440, 580, 90, "Invalidation", [
        "a 2xx POST / PUT / PATCH / DELETE gives the service a new random",
        "generation gw:gen:<service>, so older keys are never read again",
    ], kind="edge")
    d.box(60, 560, 580, 170, "cache", "HashRing + ShardedStore", [
        "every key above goes through it",
        "MD5 → 32-bit position · 160 virtual nodes per Redis node",
        "binary search: the first node point clockwise owns the key",
        "owner down → the next distinct node clockwise",
        "one Redis connection per node · 250 ms command timeout",
    ])
    # the ring
    cx, cy, r = 950, 420, 215
    d.text(cx, 120, "The ring: 2³² positions (MD5)", size=17, bold=True, align="center")
    d.ellipse(cx - r, cy - r, 2 * r, 2 * r, fill="#ffffff", stroke="#adb5bd", sw=3)
    points = []
    for n in range(3):
        for i in range(12):
            a = _ring_pos(f"cache-{n + 1}:6379#{i}")
            points.append((a, n))
            px, py = cx + r * math.sin(a), cy - r * math.cos(a)
            f, s = NODE_COLORS[n]
            d.ellipse(px - 8, py - 8, 16, 16, fill=s, stroke="#ffffff", sw=2)
    points.sort()
    key = "gw:resp:world:g7f3a:roles:/api/world/map"
    ka = _ring_pos(key)
    nxt = next(((a, n) for a, n in points if a > ka), points[0])
    owner = nxt[1]
    kx, ky = cx + r * math.sin(ka), cy - r * math.cos(ka)
    d.rect(kx - 9, ky - 9, 18, 18, fill=INK, stroke="#ffffff", sw=2, radius=2)
    end = nxt[0] if nxt[0] > ka else nxt[0] + 2 * math.pi
    rr = r - 34
    arc = [(cx + rr * math.sin(ka + (end - ka) * t / 16), cy - rr * math.cos(ka + (end - ka) * t / 16))
           for t in range(17)]
    d.arrow(arc, color=INK, sw=2.5)
    lx, ly = cx + (r + 26) * math.sin(ka), cy - (r + 26) * math.cos(ka)
    d.label(lx, ly - 8, f"key …/api/world/map\n→ first point clockwise\n→ owned by cache-{owner + 1}",
            size=12, color=INK, align="left" if math.sin(ka) >= 0 else "right")
    d.text(cx, cy - 22, "12 of the 160 points\nper node are drawn", size=13, color=MUTED, align="center")

    # the nodes
    live = [48, 52, 50]
    for n in range(3):
        f, s = NODE_COLORS[n]
        y = 180 + n * 165
        d.box(1390, y, 510, 135, "cache", f"cache-{n + 1}   redis://cache-{n + 1}:6379", [
            "Redis 7.4 · maxmemory 64 MB · allkeys-lru",
            "nothing on disk: a restarted node starts empty",
            f"live test: holds {live[n]} of 150 cached answers",
        ], fill=f, stroke=s, align="left")
