NODE_COLORS = [("#d0ebff", "#1c7ed6"), ("#ffe8cc", "#e8590c"), ("#d3f9d8", "#2f9e44")]


def _ring_pos(key: str) -> float:
    """Position on the ring as an angle in radians, clockwise from the top (as in hash-ring.ts:
    the first 4 bytes of MD5)."""
    return int(hashlib.md5(key.encode()).hexdigest()[:8], 16) / 2 ** 32 * 2 * math.pi


